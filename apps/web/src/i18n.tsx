export const dictionaries: Record<Locale, Words> = { zh, en };

/** The interface's words in the language in context. */
export const useT = () => dictionaries[useLocale()];

const KEY = "drawy.locale";
const kept = (): Locale => {
  const v = typeof localStorage === "undefined" ? null : localStorage.getItem(KEY);
  return v === "zh" || v === "en" ? v : browserLocale();
};
/** The language the user chose, kept in this browser; the browser's own until then. The
 * page's `lang` follows at once, so words picked outside components agree. */
export function useLanguage() {
  const [locale, set] = useState<Locale>(() => {
    const l = kept();
    document.documentElement.lang = langOf(l);
    return l;
  });
  const choose = (l: Locale) => {
    document.documentElement.lang = langOf(l);
    localStorage.setItem(KEY, l);
    set(l);
  };
  return [locale, choose] as const;
}

/** Changes the interface's language. */
export const ChooseLocale = createContext<(locale: Locale) => void>(() => {});

/** One press switches between Chinese and English. */
export function LanguageSwitch({ label = false }: { label?: boolean }) {
  const locale = useLocale(),
    choose = useContext(ChooseLocale),
    t = useT();
  const next: Locale = locale === "zh" ? "en" : "zh";
  return (
    <button
      type="button"
      className={cx("language")}
      aria-label={t.language + " · " + t.languages[next]}
      data-tip={label ? undefined : t.languages[next]}
      onClick={() => choose(next)}
    >
      <Languages size={16} />
      {label ? <span>{t.languages[locale]}</span> : <b>{locale === "zh" ? "中" : "EN"}</b>}
    </button>
  );
}
